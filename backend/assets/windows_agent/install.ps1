<#
LanLens outbound Windows inventory-agent installer.
The command is generated by the LanLens UI. Run it from an elevated PowerShell.
#>
[CmdletBinding()]
param(
  [Parameter(Mandatory = $true)][string]$ServerUrl,
  [Parameter(Mandatory = $true)][string]$EnrollmentToken,
  [ValidateRange(5, 1440)][int]$IntervalMinutes = 60
)

$ErrorActionPreference = 'Stop'
if (-not ([Security.Principal.WindowsPrincipal] [Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
  throw 'Run this command from an elevated PowerShell session.'
}

$ServerUrl = $ServerUrl.TrimEnd('/')
if ($ServerUrl -notmatch '^https://') { throw 'ServerUrl must use HTTPS.' }
$installDir = Join-Path $env:ProgramData 'LanLensAgent'
$sourceFile = Join-Path $installDir 'LanLensAgent.cs'
$exeFile = Join-Path $installDir 'LanLensAgent.exe'
$configFile = Join-Path $installDir 'agent.json'
$compiler = Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'
if (-not (Test-Path $compiler)) { $compiler = Join-Path $env:WINDIR 'Microsoft.NET\Framework\v4.0.30319\csc.exe' }
if (-not (Test-Path $compiler)) { throw '.NET Framework 4.x C# compiler was not found on this Windows installation.' }

New-Item -ItemType Directory -Force -Path $installDir | Out-Null
Invoke-WebRequest -UseBasicParsing -Uri "$ServerUrl/api/agents/windows/LanLensAgent.cs" -OutFile $sourceFile
& $compiler /nologo /target:exe /out:$exeFile /r:System.ServiceProcess.dll /r:System.Management.dll /r:System.Web.Extensions.dll /r:System.Net.Http.dll $sourceFile
if ($LASTEXITCODE -ne 0 -or -not (Test-Path $exeFile)) { throw 'LanLens Agent compilation failed.' }

# Query the active adapter before enrolment so LanLens can bind the agent to the
# existing discovery record (or create the correct one).
$adapter = Get-CimInstance Win32_NetworkAdapterConfiguration | Where-Object { $_.IPEnabled -and $_.MACAddress } | Select-Object -First 1
if (-not $adapter) { throw 'No active network adapter with a MAC address was found.' }
$os = Get-CimInstance Win32_OperatingSystem
$enrollment = @{ token = $EnrollmentToken; hostname = $env:COMPUTERNAME; primary_mac = $adapter.MACAddress; os_info = "$($os.Caption) $($os.Version)"; kernel_version = $os.BuildNumber; ip_addresses = @($adapter.IPAddress | Where-Object { $_ -notmatch ':' }); platform = 'windows' } | ConvertTo-Json -Compress
$response = Invoke-RestMethod -Method Post -ContentType 'application/json' -Uri "$ServerUrl/api/agents/enroll" -Body $enrollment

@{ server_url = $ServerUrl; agent_id = $response.agent_id; agent_secret = $response.agent_secret; interval_minutes = $IntervalMinutes; sequence = 0 } | ConvertTo-Json -Compress | Set-Content -Encoding UTF8 $configFile
& icacls $installDir /inheritance:r /grant:r 'SYSTEM:(OI)(CI)F' 'Administrators:(OI)(CI)F' | Out-Null

if (Get-Service -Name LanLensAgent -ErrorAction SilentlyContinue) { Stop-Service LanLensAgent -Force -ErrorAction SilentlyContinue; & sc.exe delete LanLensAgent | Out-Null; Start-Sleep -Seconds 2 }
& sc.exe create LanLensAgent binPath= "`"$exeFile`"" start= auto DisplayName= "LanLens Outbound Inventory Agent" | Out-Null
& sc.exe description LanLensAgent "Outbound HTTPS inventory reporting for LanLens" | Out-Null
& sc.exe failure LanLensAgent reset= 86400 actions= restart/5000/restart/5000/restart/30000 | Out-Null
Start-Service LanLensAgent
Write-Host 'LanLens Agent was installed, enrolled and started.' -ForegroundColor Green
